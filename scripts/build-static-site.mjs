#!/usr/bin/env node
/**
 * Build a fully static copy of the public clinic site (GitHub Pages).
 *
 * The production app (Vercel) keeps the staff dashboard, Server Actions and
 * Supabase integration. GitHub Pages can only serve static files, so this
 * script assembles a build that contains the public routes only:
 *
 *   1. copy the app into `.static-build/`
 *   2. drop the server-only routes (dashboard, appointments, patients,
 *      dentists, settings, login), the middleware and the server actions
 *   3. swap `src/app/actions.ts` for a demo stub with the same API surface
 *   4. build with `output: 'export'` and the GitHub Pages base path
 *
 * Usage:  node scripts/build-static-site.mjs
 * Env:    NEXT_PUBLIC_BASE_PATH  (e.g. "/nova-dental")
 *         NEXT_PUBLIC_APP_URL    (canonical URL used by sitemap/OG tags)
 */

import { cp, mkdir, readFile, rm, symlink, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const workdir = path.join(root, '.static-build');
const outDir = path.join(workdir, 'out');

const basePath = (process.env.NEXT_PUBLIC_BASE_PATH || '').replace(/\/$/, '');
const siteUrl =
  process.env.NEXT_PUBLIC_APP_URL ||
  (basePath ? `https://ame07316-del.github.io${basePath}` : 'http://localhost:3000');

const COPY_ENTRIES = [
  'src',
  'public',
  'package.json',
  'package-lock.json',
  'postcss.config.js',
  'tailwind.config.js',
  'tsconfig.json',
];

const SERVER_ONLY = [
  // Routes that need cookies/Supabase on the server.
  'src/app/dashboard',
  'src/app/appointments',
  'src/app/patients',
  'src/app/dentists',
  'src/app/settings',
  // Staff sign-in has no meaning without the staff area.
  'src/app/login',
  'src/app/guard.ts',
];

function log(message) {
  console.log(`\u001b[36m[static]\u001b[0m ${message}`);
}

async function main() {
  log(`Preparing ${path.relative(root, workdir)} (base path: "${basePath || '/'}")`);

  // Remove the dependency symlink first so a recursive delete can never walk
  // into the repo's node_modules.
  await rm(path.join(workdir, 'node_modules'), { force: true });
  await rm(workdir, { recursive: true, force: true });
  await mkdir(workdir, { recursive: true });

  for (const entry of COPY_ENTRIES) {
    const from = path.join(root, entry);
    if (!existsSync(from)) continue;
    await cp(from, path.join(workdir, entry), { recursive: true });
  }

  for (const entry of SERVER_ONLY) {
    await rm(path.join(workdir, entry), { recursive: true, force: true });
  }

  // Same public API, no Server Actions.
  const stub = await readFile(path.join(root, 'scripts/static/actions.stub.ts'), 'utf8');
  await writeFile(path.join(workdir, 'src/app/actions.ts'), stub);

  // Static Next config: no headers() (static hosts don't send them), no
  // standalone output, unoptimized images and the GitHub Pages base path.
  const staticConfig = `/** Generated by scripts/build-static-site.mjs — do not edit. */
const basePath = ${JSON.stringify(basePath)};

/** @type {import('next').NextConfig} */
const nextConfig = {
  output: 'export',
  trailingSlash: true,
  basePath,
  reactStrictMode: true,
  poweredByHeader: false,
  images: {
    unoptimized: true,
  },
};

module.exports = nextConfig;
`;
  await writeFile(path.join(workdir, 'next.config.js'), staticConfig);

  // Reuse the already-installed dependencies instead of reinstalling them.
  const nodeModules = path.join(root, 'node_modules');
  if (existsSync(nodeModules)) {
    await symlink(nodeModules, path.join(workdir, 'node_modules'), 'dir');
  }

  // Use the repo's own Next.js binary (npx could resolve a newer major).
  const nextBin = path.join(root, 'node_modules/next/dist/bin/next');
  if (!existsSync(nextBin)) {
    console.error('[static] Next.js is not installed — run `npm install` first.');
    process.exit(1);
  }

  log('Running next build (static export)…');
  const result = spawnSync(process.execPath, [nextBin, 'build'], {
    cwd: workdir,
    stdio: 'inherit',
    env: {
      ...process.env,
      NEXT_TELEMETRY_DISABLED: '1',
      NEXT_PUBLIC_BASE_PATH: basePath,
      NEXT_PUBLIC_STATIC_SITE: '1',
      NEXT_PUBLIC_APP_URL: siteUrl,
    },
  });

  if (result.status !== 0) {
    console.error('[static] Build failed.');
    process.exit(result.status ?? 1);
  }

  if (!existsSync(outDir)) {
    console.error('[static] Expected export output in out/ but it is missing.');
    process.exit(1);
  }

  log(`Done. Static site: ${path.relative(root, outDir)} (canonical: ${siteUrl})`);
}

main().catch((error) => {
  console.error('[static] Unexpected error:', error);
  process.exit(1);
});
